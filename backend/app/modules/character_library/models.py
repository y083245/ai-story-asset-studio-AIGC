"""SQLAlchemy ORM models for the Character Library module.

Exclusive write ownership:
- characters
- character_versions
- generation_tasks (task_type = "character_regenerate")

Read-only references:
- character reference assets from M11 (not tracked here)

Design notes:
- Every user edit on a character creates a CharacterVersion row before
  the Character row is mutated.
- character_id is a stable human-readable string (CH_001, CH_002, ...)
  assigned by the M00 ID factory.
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime
from typing import Any

from sqlalchemy import DateTime, ForeignKeyConstraint, Index, Integer, String, Text, func
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.contracts.enums import TaskStatus
from app.db.base import Base, TimestampMixin, UUIDMixin


class Character(Base, UUIDMixin, TimestampMixin):
    """Character master table — one row per story character."""

    __tablename__ = "characters"
    __table_args__ = (Index("ix_characters_project_character_id", "project_id", "character_id", unique=True),)

    # ---- Identity ----
    project_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False, index=True, comment="所属项目 ID")
    character_id: Mapped[str] = mapped_column(String(50), nullable=False, index=True, comment="稳定角色 ID，如 CH_001")
    name: Mapped[str] = mapped_column(String(100), nullable=False, comment="角色规范名称")
    aliases: Mapped[list[str] | None] = mapped_column(JSONB, nullable=True, comment="别名列表 (合并后的称呼/外号)")
    role_type: Mapped[str] = mapped_column(
        String(20), nullable=False, server_default="配角", default="配角", comment="角色定位: 主角/配角/反派/路人"
    )
    sort_order: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default="0", default=0, comment="在项目内的排序序号"
    )

    # ---- Physical Appearance (14 fields) ----
    gender: Mapped[str | None] = mapped_column(String(10), nullable=True, comment="性别")
    age: Mapped[str | None] = mapped_column(String(20), nullable=True, comment="年龄")
    height: Mapped[str | None] = mapped_column(String(20), nullable=True, comment="身高")
    body_type: Mapped[str | None] = mapped_column(String(30), nullable=True, comment="体型")
    face_shape: Mapped[str | None] = mapped_column(String(30), nullable=True, comment="脸型")
    facial_bone_structure: Mapped[str | None] = mapped_column(String(50), nullable=True, comment="面部骨骼结构")
    skin_tone: Mapped[str | None] = mapped_column(String(30), nullable=True, comment="肤色")
    eyes: Mapped[str | None] = mapped_column(String(50), nullable=True, comment="眼睛")
    eyebrows: Mapped[str | None] = mapped_column(String(30), nullable=True, comment="眉毛")
    nose: Mapped[str | None] = mapped_column(String(50), nullable=True, comment="鼻子")
    mouth: Mapped[str | None] = mapped_column(String(50), nullable=True, comment="嘴巴")
    hair_color: Mapped[str | None] = mapped_column(String(30), nullable=True, comment="发色")
    hair_style: Mapped[str | None] = mapped_column(String(100), nullable=True, comment="发型")

    # ---- Clothing & Demeanour ----
    default_outfit: Mapped[str | None] = mapped_column(Text, nullable=True, comment="默认服装")
    outfit_details: Mapped[str | None] = mapped_column(Text, nullable=True, comment="服装详细描述")
    shoes: Mapped[str | None] = mapped_column(String(100), nullable=True, comment="鞋子")
    accessories: Mapped[str | None] = mapped_column(String(200), nullable=True, comment="配饰")

    # ---- Character Traits ----
    identity: Mapped[str | None] = mapped_column(String(200), nullable=True, comment="身份")
    personality: Mapped[str | None] = mapped_column(Text, nullable=True, comment="性格描述")
    relationship_to_others: Mapped[list[dict[str, str]] | None] = mapped_column(
        JSONB, nullable=True, comment='与他人的关系，如 [{"character_id":"CH_002","relation":"恋人"}]'
    )
    first_appearance: Mapped[str | None] = mapped_column(
        String(100), nullable=True, comment="首次出场定位，如「第1幕」"
    )
    emotion_pack: Mapped[list[str] | None] = mapped_column(JSONB, nullable=True, comment="情绪包 (表情标签列表)")

    # ---- Consistency Controls (generated by consistency.py) ----
    consistency_tag: Mapped[str | None] = mapped_column(
        Text, nullable=True, comment="一致性标签, key=value逗号分隔, 供Image/Video模块拼接prompt"
    )
    forbidden_changes: Mapped[list[str] | None] = mapped_column(JSONB, nullable=True, comment="禁止修改的属性列表")

    # ---- Asset Plan (generated by image_plan.py) ----
    reference_image_plan: Mapped[list[dict[str, str]] | None] = mapped_column(
        JSONB, nullable=True, comment="参考图计划, 供 M11 Image Asset 使用"
    )
    canonical_asset_id: Mapped[str | None] = mapped_column(
        String(500), nullable=True, comment="Canonical reference asset storage_path/id"
    )
    reference_assets: Mapped[list[str] | None] = mapped_column(
        JSONB, nullable=True, comment="已生成的参考图 asset_id 列表 (由 M11 回填)"
    )

    # ---- Relationships ----
    versions: Mapped[list[CharacterVersion]] = relationship(
        "CharacterVersion", back_populates="character", cascade="all, delete-orphan"
    )

    def __repr__(self) -> str:
        return f"<Character character_id={self.character_id!r} name={self.name!r}>"


class CharacterVersion(Base, UUIDMixin):
    """Version history for a character — created before every user edit."""

    __tablename__ = "character_versions"
    __table_args__ = (
        ForeignKeyConstraint(
            ["project_id", "character_id"],
            ["characters.project_id", "characters.character_id"],
            ondelete="CASCADE",
        ),
    )

    project_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False, index=True, comment="所属项目 ID")
    character_id: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        index=True,
        comment="所属角色 ID",
    )
    version_number: Mapped[int] = mapped_column(Integer, nullable=False, comment="版本号 (从1递增)")
    changed_fields: Mapped[list[str]] = mapped_column(JSONB, nullable=False, comment="本次修改的字段列表")
    previous_values: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False, comment="修改前的字段值快照")
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        server_default=func.now(),
        nullable=False,
    )

    # ---- Relationships ----
    character: Mapped[Character] = relationship("Character", back_populates="versions")

    def __repr__(self) -> str:
        return f"<CharacterVersion character_id={self.character_id!r} v{self.version_number}>"


class GenerationTask(Base):
    """Lightweight generation task record for character regeneration.

    This table tracks the status of a regenerate request so that the
    Workflow module can pick it up and dispatch the actual work to M11.
    """

    __tablename__ = "generation_tasks"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    project_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False, index=True, comment="所属项目 ID")
    task_type: Mapped[str] = mapped_column(
        String(50), nullable=False, default="character_regenerate", comment="任务类型"
    )
    target_id: Mapped[str] = mapped_column(String(50), nullable=False, comment="目标角色 ID (CH_001)")
    status: Mapped[str] = mapped_column(String(20), nullable=False, default=TaskStatus.PENDING, comment="任务状态")
    payload: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True, comment="任务 payload")
    result: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True, comment="任务结果")
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        server_default=func.now(),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        server_default=func.now(),
        onupdate=lambda: datetime.now(UTC),
        nullable=False,
    )

    def __repr__(self) -> str:
        return f"<GenerationTask type={self.task_type!r} target={self.target_id!r} status={self.status!r}>"
